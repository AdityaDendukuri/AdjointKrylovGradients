"""
Generate the stationary one-sided-termination example used in panel (a) of the
stopping-rule figure.

The first example is a symmetric reflecting random-walk CTMC started at its
stationary distribution. The forward Arnoldi process terminates after one
step, so the multiplicative residual estimate is zero while the adjoint and
the Fréchet derivative remain unresolved. The script also retains the earlier
pure-birth audit as a separate CSV. Panel (b) is generated by
`brusselator_error_control.jl`. Equation numbers (59) and (60) refer to the
published Numerical Linear Algebra with Applications version.

Run from the repository root:

    julia --project=experiments experiments/paired_norm_stopping_failure.jl
"""

using LinearAlgebra, SparseArrays, Printf
using CSV, DataFrames
using FastGaussQuadrature: gausslegendre

const N = parse(Int, get(ENV, "CERT_N", "80"))
const TARGET = parse(Int, get(ENV, "CERT_TARGET", "15"))
const RATE = parse(Float64, get(ENV, "CERT_RATE", "1.0"))
const FINAL_TIME = parse(Float64, get(ENV, "CERT_TIME", "20.0"))
const MAX_DEPTH = parse(Int, get(ENV, "CERT_MAX_DEPTH", "50"))
const EDGE_COLUMN = parse(Int, get(ENV, "CERT_EDGE_COLUMN", "8"))
const OUTPUT = get(
    ENV,
    "CERT_OUTPUT",
    joinpath(@__DIR__, "..", "paper", "figures", "paired_norm_stopping_failure.csv"),
)
const ONE_SIDED_OUTPUT = get(
    ENV,
    "CERT_ONE_SIDED_OUTPUT",
    joinpath(@__DIR__, "..", "paper", "figures", "one_sided_stopping_failure.csv"),
)
const NEAR_ONE_SIDED_OUTPUT = get(
    ENV,
    "CERT_NEAR_ONE_SIDED_OUTPUT",
    joinpath(@__DIR__, "..", "paper", "figures", "near_one_sided_stopping_failure.csv"),
)
const STATIONARY_N = parse(Int, get(ENV, "CERT_STATIONARY_N", "200"))
const STATIONARY_TIME = parse(Float64, get(ENV, "CERT_STATIONARY_TIME", "80.0"))
const STATIONARY_MAX_DEPTH = parse(Int, get(ENV, "CERT_STATIONARY_MAX_DEPTH", "30"))

function pure_birth_direction(n)
    rows = Int[]
    cols = Int[]
    vals = Float64[]
    for column in 1:(n - 1)
        push!(rows, column, column + 1)
        push!(cols, column, column)
        push!(vals, -1.0, 1.0)
    end
    sparse(rows, cols, vals, n, n)
end

function single_birth_edge_direction(n, column)
    1 <= column < n || error("edge column must lie in 1:(n-1)")
    sparse([column, column + 1], [column, column], [-1.0, 1.0], n, n)
end

function arnoldi_with_residual(A, start, depth; tolerance=1e-14)
    n = length(start)
    requested = min(depth, n)
    V = zeros(eltype(start), n, requested + 1)
    H = zeros(eltype(start), requested + 1, requested)
    beta = norm(start)
    beta > tolerance || error("Arnoldi start must be nonzero")
    V[:, 1] .= start ./ beta
    used = requested
    for column in 1:requested
        work = A * view(V, :, column)
        for row in 1:column
            H[row, column] = dot(view(V, :, row), work)
            work .-= H[row, column] .* view(V, :, row)
        end
        H[column + 1, column] = norm(work)
        if H[column + 1, column] <= tolerance
            used = column
            break
        end
        V[:, column + 1] .= work ./ H[column + 1, column]
    end
    (
        V=V[:, 1:used],
        H=H[1:used, 1:used],
        beta=beta,
        residual_coefficient=H[used + 1, used],
        residual_vector=V[:, used + 1],
        depth=used,
    )
end

function exp_frechet_matrix(A, direction, time)
    n = size(A, 1)
    exp([
        time .* Matrix(A) time .* Matrix(direction)
        zeros(eltype(A), n, n) time .* Matrix(A)
    ])[1:n, (n + 1):(2n)]
end

function projected_core(forward, adjoint, time)
    mf = forward.depth
    ma = adjoint.depth
    block = zeros(Float64, ma + mf, ma + mf)
    block[1:ma, 1:ma] .= adjoint.H
    block[(ma + 1):end, (ma + 1):end] .= forward.H'
    block[1, ma + 1] = adjoint.beta * forward.beta
    exp(time .* block)[1:ma, (ma + 1):end]
end

function projected_matrix(forward, adjoint, time)
    adjoint.V * projected_core(forward, adjoint, time) * forward.V'
end

function kandolf_39_estimate(forward, adjoint, time)
    m = forward.depth
    adjoint.depth == m || return NaN
    e1e1 = zeros(m, m)
    e1e1[1, 1] = 1.0
    augmented = zeros(Float64, 4m, 4m)
    augmented[1:m, 1:m] .= time .* adjoint.H
    augmented[1:m, (m + 1):(2m)] .= -e1e1
    augmented[(m + 1):(2m), (m + 1):(2m)] .= time .* forward.H'
    augmented[(m + 1):(2m), (2m + 1):(3m)] .= Matrix{Float64}(I, m, m)
    augmented[(2m + 1):(3m), (3m + 1):(4m)] .= Matrix{Float64}(I, m, m)
    scale = forward.beta * adjoint.beta *
        abs(time * forward.residual_coefficient) *
        abs(time * adjoint.residual_coefficient)
    scale * abs(exp(augmented)[m, 3m + 1])
end

function additive_one_sided_bound(forward, time; order=96)
    # When A is contractive in the Euclidean norm and the other trajectory is
    # exact with unit norm, variation of constants gives
    # ||L-L_m||_F <= |h| integral_0^1 (1-s)||r(s)||_2 ds.
    nodes, weights = gausslegendre(order)
    nodes .= (nodes .+ 1) ./ 2
    weights ./= 2
    m = forward.depth
    coefficient = abs(time * forward.beta * forward.residual_coefficient)
    abs(time) * sum(zip(nodes, weights)) do (s, weight)
        reduced = exp((s * time) .* forward.H)
        weight * (1 - s) * coefficient * abs(reduced[m, 1])
    end
end

function reflecting_walk_generator(n)
    n >= 3 || error("stationary CTMC dimension must be at least three")
    A = spdiagm(-1 => ones(n - 1), 1 => ones(n - 1))
    diagonal = fill(-2.0, n)
    diagonal[1] = -1.0
    diagonal[end] = -1.0
    A + spdiagm(0 => diagonal)
end

function integrated_exponential_action(A, start, time)
    decomposition = eigen(Symmetric(Matrix(A)))
    coefficients = decomposition.vectors' * start
    factors = map(decomposition.values) do value
        abs(value) <= 1e-13 ? time : expm1(time * value) / value
    end
    decomposition.vectors * (factors .* coefficients)
end

function run_one_sided_example()
    A = reflecting_walk_generator(STATIONARY_N)
    stationary = ones(STATIONARY_N) ./ sqrt(STATIONARY_N)
    unresolved = zeros(STATIONARY_N)
    unresolved[1] = 1.0
    time = STATIONARY_TIME
    exact_vector = integrated_exponential_action(A, unresolved, time)
    exact = exact_vector * stationary'
    stationary_basis = arnoldi_with_residual(A, stationary, 1)
    @assert stationary_basis.depth == 1
    @assert abs(stationary_basis.residual_coefficient) <= 1e-14

    rows = NamedTuple[]
    for depth in 1:STATIONARY_MAX_DEPTH
        unresolved_basis = arnoldi_with_residual(A, unresolved, depth)
        approximation = projected_matrix(stationary_basis, unresolved_basis, time)
        true_error = norm(approximation - exact)
        additive_bound = additive_one_sided_bound(unresolved_basis, time)
        multiplicative_estimate =
            abs(stationary_basis.residual_coefficient) *
            abs(unresolved_basis.residual_coefficient)
        push!(rows, (
            adjoint_depth=depth,
            true_error_frobenius=true_error,
            multiplicative_residual_estimate=multiplicative_estimate,
            additive_residual_bound=additive_bound,
            unresolved_residual_coefficient=unresolved_basis.residual_coefficient,
            state_dimension=STATIONARY_N,
            interval_length=time,
        ))
    end
    data = DataFrame(rows)
    @assert data.true_error_frobenius[1] > 1.0
    @assert maximum(data.multiplicative_residual_estimate) <= 1e-14
    @assert all(data.additive_residual_bound .+ 1e-10 .>= data.true_error_frobenius)
    mkpath(dirname(ONE_SIDED_OUTPUT))
    CSV.write(ONE_SIDED_OUTPUT, data)
    @printf(
        "stationary CTMC: n=%d, h=%.1f, depth-1 error=%.6f, multiplicative estimate=%.1e, additive bound=%.6f\n",
        STATIONARY_N,
        time,
        data.true_error_frobenius[1],
        data.multiplicative_residual_estimate[1],
        data.additive_residual_bound[1],
    )
    println("saved ", ONE_SIDED_OUTPUT)
end

function run_near_one_sided_example()
    A = reflecting_walk_generator(STATIONARY_N)
    stationary = ones(STATIONARY_N) ./ sqrt(STATIONARY_N)
    perturbation = zeros(STATIONARY_N)
    perturbation[1] = 1.0
    perturbation .-= dot(stationary, perturbation) .* stationary
    perturbation ./= norm(perturbation)
    unresolved = zeros(STATIONARY_N)
    unresolved[1] = 1.0
    time = STATIONARY_TIME

    exact_stationary = integrated_exponential_action(A, unresolved, time) * stationary'
    exact_perturbation = exp_frechet_matrix(A, unresolved * perturbation', time)
    adjoint_basis = arnoldi_with_residual(A, unresolved, 1)

    rows = NamedTuple[]
    for epsilon in 10.0 .^ (-1:-1:-10)
        start = stationary + epsilon .* perturbation
        forward_basis = arnoldi_with_residual(A, start, 1)
        approximation = projected_matrix(forward_basis, adjoint_basis, time)
        exact = exact_stationary + epsilon .* exact_perturbation
        exact_norm = norm(exact)
        true_error = norm(approximation - exact)
        estimate = kandolf_39_estimate(forward_basis, adjoint_basis, time)
        push!(rows, (
            perturbation=epsilon,
            true_error_frobenius=true_error,
            exact_frechet_frobenius=exact_norm,
            relative_true_error=true_error / exact_norm,
            kandolf_59_estimate=estimate,
            relative_kandolf_59_estimate=estimate / exact_norm,
            underestimate_factor=true_error / max(estimate, eps()),
            nearly_stationary_residual_coefficient=forward_basis.residual_coefficient,
            other_residual_coefficient=adjoint_basis.residual_coefficient,
            state_dimension=STATIONARY_N,
            interval_length=time,
        ))
    end

    data = DataFrame(rows)
    @assert minimum(data.true_error_frobenius) > 1.0
    @assert data.kandolf_59_estimate[end] < data.kandolf_59_estimate[1] * 1e-8
    mkpath(dirname(NEAR_ONE_SIDED_OUTPUT))
    CSV.write(NEAR_ONE_SIDED_OUTPUT, data)
    @printf(
        "near-stationary CTMC: error %.6f -> %.6f while estimate %.3e -> %.3e\n",
        data.true_error_frobenius[1],
        data.true_error_frobenius[end],
        data.kandolf_59_estimate[1],
        data.kandolf_59_estimate[end],
    )
    println("saved ", NEAR_ONE_SIDED_OUTPUT)
end

function main()
2 <= TARGET < N || error("CERT_TARGET must lie in 2:(CERT_N-1)")
2 <= MAX_DEPTH < N || error("CERT_MAX_DEPTH must lie in 2:(CERT_N-1)")

generator_direction = pure_birth_direction(N)
direction = single_birth_edge_direction(N, EDGE_COLUMN)
generator = RATE .* generator_direction
initial = zeros(N)
initial[1] = 1.0
terminal = zeros(N)
terminal[TARGET + 1] = 1.0

adjoint_block = FINAL_TIME .* Matrix(generator')
forcing = FINAL_TIME .* (terminal * initial')
exact_matrix = exp([
    adjoint_block forcing
    zeros(N, N) adjoint_block
])[1:N, (N + 1):(2N)]
exact_gradient = real(dot(exact_matrix, Matrix(direction)))

rows = NamedTuple[]
previous_gradient = NaN
previous_matrix = nothing
for depth in 2:MAX_DEPTH
    forward = arnoldi_with_residual(generator, initial, depth)
    adjoint = arnoldi_with_residual(generator', terminal, depth)
    approximation = projected_matrix(forward, adjoint, FINAL_TIME)
    gradient = real(dot(approximation, Matrix(direction)))
    gradient_error = abs(gradient - exact_gradient)
    successive_gradient = isfinite(previous_gradient) ?
        abs(gradient - previous_gradient) : NaN
    matrix_error = norm(approximation - exact_matrix)
    successive_matrix = previous_matrix === nothing ? NaN :
        norm(approximation - previous_matrix)

    kandolf_39 = kandolf_39_estimate(forward, adjoint, FINAL_TIME)

    push!(rows, (
        depth=depth,
        exact_gradient=exact_gradient,
        projected_gradient=gradient,
        gradient_error=gradient_error,
        successive_gradient_estimate=successive_gradient,
        kandolf_39_estimate=kandolf_39,
        matrix_error_frobenius=matrix_error,
        successive_matrix_estimate=successive_matrix,
        forward_residual_coefficient=forward.residual_coefficient,
        adjoint_residual_coefficient=adjoint.residual_coefficient,
    ))
    @printf(
        "m=%2d  error=%9.2e  estimate59=%9.2e  estimate60=%9.2e\n",
        depth,
        matrix_error,
        kandolf_39,
        successive_matrix,
    )
    previous_gradient = gradient
    previous_matrix = approximation
end

data = DataFrame(rows)
stop_index = findfirst(
    isfinite.(data.successive_matrix_estimate) .&
    (data.successive_matrix_estimate .<= 1e-4)
)
@assert stop_index !== nothing
@assert data.depth[stop_index] == 3
@assert data.matrix_error_frobenius[stop_index] >= 1.0

mkpath(dirname(OUTPUT))
CSV.write(OUTPUT, data)
@printf("exact gradient: %.12e\n", exact_gradient)
println("saved ", OUTPUT)
end

run_one_sided_example()
run_near_one_sided_example()
main()
